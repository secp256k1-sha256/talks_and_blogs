#!/usr/bin/env bash
# ============================================================================
# bench_versions.sh -- full dishonest-benchmark suite on Windows localhost,
# PostgreSQL 17 then 18, every test run twice (two full rounds), with a
# complete reset before EVERY run.  Run from Git Bash in an elevated session.
#
# Per version:
#   * stop every other PostgreSQL service, start this one
#   * back up postgresql.auto.conf, start from an EMPTY auto.conf + baseline
#     (README reset_settings.sql; PG17 skips the PG18-only io_* settings),
#     restart so restart-only settings are active, verify nothing pending
#   * 15 s warm-up
#   * round 1: tests 1..20, round 2: tests 1..20; before each run:
#       re-apply baseline + reload + verify, DROP/CREATE DATABASE, schema,
#       procs, SQL functions, (drop FK), VACUUM ANALYZE, cheat + verify,
#       CHECKPOINT, pgbench 120 s
#   * restore the original auto.conf, stop the service
# ============================================================================
set -uo pipefail

ROOT=/c/cld/talks_and_blogs/dishonest_benchmark
SQL=$ROOT/sql
OUT="${OUT:-$ROOT/test_reports/20261010_pg18_devdrive_r1}"
VERSIONS="${VERSIONS:-17 18}"
ROUNDS="${ROUNDS:-2}"
DUR="${DUR:-120}"; WARM="${WARM:-15}"; CLIENTS=32; THREADS=8
export PGHOST=localhost PGPORT=5432 PGUSER=postgres PGPASSWORD=6174316
DB=pgbench_darkside

log() { echo "[$(date +%H:%M:%S)] $*"; }
die() { log "FATAL: $*"; exit 1; }
svc() { powershell.exe -NoProfile -Command "$1-Service postgresql-x64-$2 ${3:-} -WarningAction SilentlyContinue" >/dev/null 2>&1; }

CSV_HEADER='"idx","method","script","protocol","tps","ops_per_txn","ops_per_sec","lat_ms","wal_bytes","wal_per_tx","txns","x_vs_baseline","x_vs_case0"'

# name | script | protocol | ops/txn | drop fk | cheat (ALTER SYSTEM list) | db pre-step
ALL_DUR="synchronous_commit=off;full_page_writes=off;fsync=off"
CKPT="max_wal_size=64GB;checkpoint_timeout=30min"
ALL_CHEATS="$ALL_DUR;$CKPT"
TESTS=(
  "Case 0: bad code / missing index|honest-ish.sql|simple|1|||DROP INDEX IF EXISTS bench_audit_created_at_audit_id_idx"
  "Indexed baseline|honest-ish.sql|simple|1|||"
  "synchronous_commit=off|honest-ish.sql|simple|1||synchronous_commit=off|"
  "full_page_writes=off|honest-ish.sql|simple|1||full_page_writes=off|"
  "fsync=off|honest-ish.sql|simple|1||fsync=off|"
  "checkpoint tuning|honest-ish.sql|simple|1||$CKPT|"
  "all durability off|honest-ish.sql|simple|1||$ALL_DUR|"
  "less work (drop FK/SELECT/audit)|less_work.sql|simple|1|drop||"
  "UNLOGGED ledger/audit|unlogged.sql|simple|1|||"
  "stored procedure|procedure.sql|simple|1|||"
  "prepared protocol|honest-ish.sql|prepared|1|||"
  "prepared + pipelined|honest-ish-pipeline.sql|prepared|1|||"
  "batching x8|batch.sql|simple|8|||"
  "batching x32|batch32.sql|simple|32|||"
  "stored proc + prepared|procedure.sql|prepared|1|||"
  "all cheats + batch x32|batch32.sql|prepared|32|drop|$ALL_CHEATS|"
  "all cheats + mega-batch x1000|megabatch.sql|prepared|1000|drop|$ALL_CHEATS|"
  "stored function (SQL)|sqlfunction.sql|simple|1|||"
  "sql function + prepared|sqlfunction.sql|prepared|1|||"
  "all cheats + batch x32 (SQL fn)|batch32_sqlfn.sql|prepared|32|drop|$ALL_CHEATS|"
)

baseline_sql() {   # README reset_settings.sql; PG17 drops PG18-only io_* and effective_io_concurrency (Windows PG17 requires 0)
    local v=$1
    if (( v >= 18 )); then tr -d '\r' < "$ROOT/reset_settings.sql"
    else tr -d '\r' < "$ROOT/reset_settings.sql" | grep -viE "io_method|io_workers|io_max_concurrency|effective_io_concurrency"; fi
}

for V in $VERSIONS; do
    PGHOME="/c/Program Files/PostgreSQL/$V"; [[ $V == 18 ]] && PGHOME=/v/PostgreSQL/18   # PG18 on the Dev Drive since 2026-10-10
    BIN="$PGHOME/bin"; DATA="$PGHOME/data"
    PSQL="$BIN/psql.exe"; PGBENCH="$BIN/pgbench.exe"
    VOUT=$OUT/pg$V; mkdir -p "$VOUT/raw"
    A()  { "$PSQL" -X -q -t -A -v ON_ERROR_STOP=1 -d postgres "$@" | tr -d '\r'; }
    Bq() { "$PSQL" -X -q -t -A -v ON_ERROR_STOP=1 -d $DB "$@" | tr -d '\r'; }
    Bf() { "$PSQL" -X -q -v ON_ERROR_STOP=1 -d $DB -f "$1" >/dev/null 2>&1; }

    log "===== PostgreSQL $V ====="
    for o in 14 15 16 17 18; do [[ $o == "$V" ]] || svc Stop $o -Force; done
    # empty auto.conf + baseline, restart so restart-only settings apply
    [[ -f "$DATA/postgresql.auto.conf.pre_bench_report" ]] || cp -p "$DATA/postgresql.auto.conf" "$DATA/postgresql.auto.conf.pre_bench_report"
    printf '# Do not edit this file manually!\n# It will be overwritten by the ALTER SYSTEM command.\n' > "$DATA/postgresql.auto.conf"
    svc Restart $V -Force; svc Start $V; sleep 3
    baseline_sql $V | A >/dev/null || die "baseline apply failed"
    svc Restart $V -Force; sleep 3
    pend=$(A -c "select coalesce(string_agg(name, ','),'') from pg_settings where pending_restart")
    [[ -z $pend ]] || die "pending restart: $pend"
    A -c "select version()" > "$VOUT/environment.txt"
    A -c "select name||' = '||setting||coalesce(' '||unit,'') from pg_settings where source not in ('default','override','client','session') order by name" > "$VOUT/settings.txt"
    A -c "show wal_sync_method" | sed 's/^/wal_sync_method = /' >> "$VOUT/environment.txt"
    log "baseline active: $(A -c "select string_agg(name||'='||setting, ' ' order by name) from pg_settings where name in ('shared_buffers','max_connections','wal_buffers','fsync','synchronous_commit','wal_sync_method')")"

    # one global warm-up
    A -c "DROP DATABASE IF EXISTS $DB WITH (FORCE);" -c "CREATE DATABASE $DB;" >/dev/null
    for f in schema_load setup_objects create_sqlfn; do Bf "$SQL/$f.sql" || die "load $f"; done
    Bq -c "VACUUM (ANALYZE);" >/dev/null
    log "warm-up ${WARM}s"; "$PGBENCH" -n -c $CLIENTS -j $THREADS -T $WARM -f "$SQL/honest-ish.sql" -d $DB >/dev/null 2>&1

    for R in $(seq 1 "$ROUNDS"); do
        CSV=$VOUT/results_round$R.csv; echo "$CSV_HEADER" > "$CSV.tmp"
        i=0
        for t in "${TESTS[@]}"; do
            i=$((i+1))
            IFS='|' read -r name script proto ops fk cheat dbpre <<<"$t"
            # ---- full reset --------------------------------------------------
            baseline_sql $V | A >/dev/null || die "baseline re-apply"
            sleep 0.5
            chk=$(A -c "select string_agg(name||'='||setting, ' ' order by name) from pg_settings where name in ('fsync','full_page_writes','synchronous_commit','max_wal_size','checkpoint_timeout')")
            [[ $chk == "checkpoint_timeout=600 fsync=on full_page_writes=on max_wal_size=4096 synchronous_commit=on" ]] || die "baseline not restored: $chk"
            pr=$(A -c "select coalesce(string_agg(name, ','),'') from pg_settings where pending_restart"); [[ -z $pr ]] || die "pending restart before run: $pr"
            A -c "DROP DATABASE IF EXISTS $DB WITH (FORCE);" -c "CREATE DATABASE $DB;" >/dev/null || die "recreate db"
            for f in schema_load setup_objects create_sqlfn; do Bf "$SQL/$f.sql" || die "load $f"; done
            [[ $fk == drop ]] && Bq -c "ALTER TABLE bench_accounts DROP CONSTRAINT IF EXISTS bench_accounts_branch_id_fkey;" >/dev/null
            Bq -c "VACUUM (ANALYZE);" >/dev/null
            [[ -n $dbpre ]] && Bq -c "$dbpre;" >/dev/null
            applied="-"
            if [[ -n $cheat ]]; then
                args=(); IFS=';' read -r -a kv <<<"$cheat"
                for p in "${kv[@]}"; do args+=(-c "ALTER SYSTEM SET ${p%%=*} = '${p#*=}';"); done
                A "${args[@]}" -c "SELECT pg_reload_conf();" >/dev/null || die "cheat apply"
                sleep 1
                names=$(for p in "${kv[@]}"; do printf "'%s'," "${p%%=*}"; done); names=${names%,}
                applied=$(A -c "select string_agg(name||'='||setting, ' ' order by name) from pg_settings where name in ($names)")
            fi
            fkn=$(Bq -c "select count(*) from pg_constraint where conname='bench_accounts_branch_id_fkey'")
            idxn=$(Bq -c "select count(*) from pg_indexes where indexname='bench_audit_created_at_audit_id_idx'")
            Bq -c "CHECKPOINT;" >/dev/null
            # ---- measured run ------------------------------------------------
            log "[pg$V r$R $(printf %2d $i)/20] $name ($script, $proto) cheat=[$applied] fk=$fkn idx=$idxn"
            lsn_a=$(A -c "select pg_current_wal_lsn()")
            raw=$VOUT/raw/r${R}_$(printf %02d $i).txt
            "$PGBENCH" -n -c $CLIENTS -j $THREADS -T $DUR -M $proto -f "$SQL/$script" -d $DB > "$raw" 2>&1
            rc=$?
            lsn_b=$(A -c "select pg_current_wal_lsn()")
            wal=$(A -c "select pg_wal_lsn_diff('$lsn_b','$lsn_a')::bigint")
            out=$(tr -d '\r' < "$raw")
            tps=$(sed -nE 's/^tps = ([0-9.]+) \(without.*/\1/p' <<<"$out" | head -1); tps=${tps:-0}
            lat=$(sed -nE 's/^latency average = ([0-9.]+) ms.*/\1/p' <<<"$out" | head -1); lat=${lat:-0}
            ntx=$(sed -nE 's/^number of transactions actually processed: ([0-9]+).*/\1/p' <<<"$out" | head -1); ntx=${ntx:-0}
            nfail=$(sed -nE 's/^number of failed transactions: ([0-9]+).*/\1/p' <<<"$out" | head -1); nfail=${nfail:-0}
            opsec=$(awk -v t="$tps" -v o="$ops" 'BEGIN{printf "%.2f", t*o}')
            walpt=$(awk -v w="$wal" -v n="$ntx" 'BEGIN{ if (n>0) printf "%.1f", w/n; else print 0 }')
            echo "\"$i\",\"$name\",\"$script\",\"$proto\",\"$(printf %.2f "$tps")\",\"$ops\",\"$opsec\",\"$lat\",\"$wal\",\"$walpt\",\"$ntx\",\"\",\"\"" >> "$CSV.tmp"
            echo "$V,$R,$i,$name,$tps,$opsec,$lat,$wal,$walpt,$ntx,$nfail,$rc,$applied" >> "$OUT/all_runs_raw.log"
            log "        tps=$tps ops/s=$opsec lat=${lat}ms wal/tx=${walpt}B failed=$nfail rc=$rc"
        done
        mv "$CSV.tmp" "$CSV"   # x_vs_* columns are computed by the report step
        log "round $R done -> $CSV"
    done

    # restore this version's original config, stop it
    Bq -c "select 1" >/dev/null 2>&1
    A -c "DROP DATABASE IF EXISTS $DB WITH (FORCE);" >/dev/null
    cp -p "$DATA/postgresql.auto.conf.pre_bench_report" "$DATA/postgresql.auto.conf"
    svc Stop $V -Force
    log "PostgreSQL $V finished; original auto.conf restored; service stopped"
done
log "ALL DONE"
